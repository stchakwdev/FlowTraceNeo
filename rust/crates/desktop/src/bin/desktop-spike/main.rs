//! F3 spike: a gpui-kit `DataTable` fed live from a SpacetimeDB subscription, plus a
//! one-field form that calls the module's reducer. Throwaway; the decisions it proved
//! are in `rust/docs/adr/0002-gpui-spacetime.md`, and U1 deletes this folder.
//!
//! ```text
//! desktop-spike [--uri http://127.0.0.1:3100] [--db ft-f3-spike] [--drive threaded|tick]
//! ```
//!
//! The module is `rust/spikes/stdb-spike`; `module_bindings/` is its
//! `spacetime generate --lang rust` output, formatted with `cargo fmt`.

mod live;
#[allow(
    clippy::pedantic,
    missing_docs,
    reason = "generated by spacetime generate 2.12; regenerate rather than edit"
)]
mod module_bindings;
mod rows;
mod view;

use anyhow::{Context as _, bail};
use gpui_kit::{
    AppContext as _, Bounds, SharedString, TitlebarOptions, WindowBounds, WindowOptions, px, size,
};

use crate::live::Drive;
use crate::view::SpikeView;

/// Command-line options.
struct Args {
    uri: String,
    database: String,
    drive: Drive,
}

impl Args {
    fn parse(mut args: impl Iterator<Item = String>) -> anyhow::Result<Self> {
        let mut parsed = Self {
            uri: "http://127.0.0.1:3100".to_owned(),
            database: "ft-f3-spike".to_owned(),
            drive: Drive::Threaded,
        };
        while let Some(flag) = args.next() {
            let value = args
                .next()
                .with_context(|| format!("{flag} needs a value"))?;
            match flag.as_str() {
                "--uri" => parsed.uri = value,
                "--db" => parsed.database = value,
                "--drive" => {
                    parsed.drive = match value.as_str() {
                        "threaded" => Drive::Threaded,
                        "tick" => Drive::Tick,
                        other => bail!("--drive is threaded or tick, not {other}"),
                    }
                }
                other => bail!("unknown option {other}"),
            }
        }
        Ok(parsed)
    }
}

fn main() -> anyhow::Result<()> {
    let args = Args::parse(std::env::args().skip(1))?;
    let (conn, rx) = live::connect(&args.uri, &args.database)
        .with_context(|| format!("connecting to {} at {}", args.database, args.uri))?;
    let drive = args.drive;
    let database = SharedString::from(args.database);

    gpui_kit::application()
        .with_assets(gpui_kit::assets::Assets)
        .run(move |cx| {
            gpui_kit::init(cx);
            view::apply_theme(cx);
            let options = WindowOptions {
                titlebar: Some(TitlebarOptions {
                    title: Some("FlowTrace Books spike".into()),
                    ..Default::default()
                }),
                window_bounds: Some(WindowBounds::Windowed(Bounds::centered(
                    None,
                    size(px(1100.0), px(760.0)),
                    cx,
                ))),
                app_id: Some("flowtrace-books-spike".to_owned()),
                ..Default::default()
            };
            let opened = gpui_kit::open_window(options, cx, |window, cx| {
                cx.new(|cx| SpikeView::new(conn, rx, drive, database, window, cx))
            });
            if let Err(err) = opened {
                eprintln!("desktop-spike: could not open a window: {err:#}");
                cx.quit();
            }
        });
    Ok(())
}
